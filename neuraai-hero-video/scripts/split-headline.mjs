// Splits the outlined headline path exported from Figma (public/figma/headline.svg)
// into one path per word, so each word can be animated independently.
// Usage: node scripts/split-headline.mjs  ->  writes src/figma/headline-words.ts
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svg = readFileSync(join(root, 'public/figma/headline.svg'), 'utf8');
const d = svg.match(/ d="([^"]+)"/)[1];
const [, vbW, vbH] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/).map(Number);

// Each glyph contour starts with an absolute "M"; Figma only emits absolute M/L/H/V/C/Z.
const subpaths = d.split(/(?=M)/).map((sp) => {
  const xs = [];
  const ys = [];
  const re = /([MLHVCZ])([^MLHVCZ]*)/g;
  let m;
  while ((m = re.exec(sp))) {
    const nums = (m[2].match(/-?[\d.]+(?:e-?\d+)?/g) || []).map(Number);
    if (m[1] === 'H') xs.push(...nums);
    else if (m[1] === 'V') ys.push(...nums);
    else
      for (let i = 0; i < nums.length; i += 2) {
        xs.push(nums[i]);
        ys.push(nums[i + 1]);
      }
  }
  return {d: sp, minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys)};
});

const LINE_SPLIT_Y = vbH / 2;
const WORD_GAP = 10; // word spaces are ~16-22 units at 64px; glyph gaps are < 7
const words = [];
for (const line of [0, 1]) {
  const inLine = subpaths.filter((s) => ((s.minY + s.maxY) / 2 < LINE_SPLIT_Y ? 0 : 1) === line);
  let current = null;
  for (const s of inLine) {
    if (!current || s.minX - current.maxX > WORD_GAP) {
      current = {line, parts: [], minX: s.minX, maxX: s.maxX, minY: s.minY, maxY: s.maxY};
      words.push(current);
    }
    current.parts.push(s.d);
    current.minX = Math.min(current.minX, s.minX);
    current.maxX = Math.max(current.maxX, s.maxX);
    current.minY = Math.min(current.minY, s.minY);
    current.maxY = Math.max(current.maxY, s.maxY);
  }
}

const out = words.map((w) => ({
  line: w.line,
  d: w.parts.join(''),
  bbox: [w.minX, w.minY, w.maxX - w.minX, w.maxY - w.minY].map((v) => +v.toFixed(1)),
}));

const file = `// Generated by scripts/split-headline.mjs from public/figma/headline.svg — do not edit.
export const HEADLINE_VIEWBOX = {width: ${vbW}, height: ${vbH}};
export const HEADLINE_WORDS: {line: 0 | 1; d: string; bbox: [number, number, number, number]}[] = ${JSON.stringify(out, null, 2)};
`;
mkdirSync(join(root, 'src/figma'), {recursive: true});
writeFileSync(join(root, 'src/figma/headline-words.ts'), file);
console.log(`${out.length} words:`, out.map((w) => `L${w.line} [${w.bbox.join(', ')}]`).join(' | '));
